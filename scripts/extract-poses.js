// Extracts the avatar's Condition poses - single frames of Quaternius's
// Universal Animation Library (CC0), which shares the avatar bodies'
// skeleton - into src/js/avatar-poses.js (copied to gmscreen/src/js/), so
// the apps ship a few KB of bone rotations instead of the 7.6 MB library.
//
//   node scripts/extract-poses.js "<path to>/UAL1_Standard.glb"
//
// Only needed again to change which frames are used (POSES below).
const fs = require('fs');
const path = require('path');

// id -> animation and the moment in it (fraction of its length).
// See avatar-parts.js applyPose for how each is used.
const POSES = {
  down: { clip: 'Death01', at: 0.7 }, // flat on the ground
  kneel: { clip: 'Fixing_Kneeling', at: 0.5 }, // right knee down, head bowed
  hunch: { clip: 'Crouch_Idle_Loop', at: 0.5 }, // hunched and low
  stagger: { clip: 'Jump_Land', at: 0.3 } // staggered, slumped
};

const file = process.argv[2];
if (!file) {
  console.error('usage: node scripts/extract-poses.js <UAL1_Standard.glb>');
  process.exit(1);
}

const buf = fs.readFileSync(file);
const jsonLen = buf.readUInt32LE(12);
const gltf = JSON.parse(buf.slice(20, 20 + jsonLen).toString('utf8'));
const binStart = 20 + jsonLen + 8;

function accessor(index) {
  const acc = gltf.accessors[index];
  const view = gltf.bufferViews[acc.bufferView];
  if (acc.componentType !== 5126) throw new Error('expected float accessor');
  const width = { SCALAR: 1, VEC3: 3, VEC4: 4 }[acc.type];
  const offset = binStart + (view.byteOffset || 0) + (acc.byteOffset || 0);
  const stride = view.byteStride || width * 4;
  const out = [];
  for (let i = 0; i < acc.count; i++) {
    const row = [];
    for (let c = 0; c < width; c++) row.push(buf.readFloatLE(offset + i * stride + c * 4));
    out.push(row);
  }
  return out;
}

function slerp(a, b, t) {
  let dot = a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3];
  const bb = dot < 0 ? b.map((v) => -v) : b;
  dot = Math.abs(dot);
  if (dot > 0.9995) {
    const r = a.map((v, i) => v + (bb[i] - v) * t);
    const len = Math.hypot(...r);
    return r.map((v) => v / len);
  }
  const theta = Math.acos(dot);
  const s = Math.sin(theta);
  const wa = Math.sin((1 - t) * theta) / s;
  const wb = Math.sin(t * theta) / s;
  return a.map((v, i) => v * wa + bb[i] * wb);
}

function sample(sampler, time, rotation) {
  const times = accessor(sampler.input).map((r) => r[0]);
  const values = accessor(sampler.output);
  if (time <= times[0]) return values[0];
  for (let i = 1; i < times.length; i++) {
    if (time <= times[i]) {
      const t = (time - times[i - 1]) / (times[i] - times[i - 1]);
      if (sampler.interpolation === 'STEP') return values[i - 1];
      return rotation ? slerp(values[i - 1], values[i], t) : values[i - 1].map((v, c) => v + (values[i][c] - v) * t);
    }
  }
  return values[values.length - 1];
}

const round = (v) => Math.round(v * 1e5) / 1e5;
const result = {};
for (const [id, { clip, at }] of Object.entries(POSES)) {
  const anim = gltf.animations.find((a) => a.name === clip);
  if (!anim) throw new Error(`no animation ${clip}`);
  const duration = Math.max(...anim.samplers.map((s) => gltf.accessors[s.input].max[0]));
  const time = duration * at;
  const pose = { q: {}, pelvis: null };
  for (const ch of anim.channels) {
    const name = gltf.nodes[ch.target.node].name;
    const sampler = anim.samplers[ch.sampler];
    if (ch.target.path === 'rotation') pose.q[name] = sample(sampler, time, true).map(round);
    if (ch.target.path === 'translation' && name === 'pelvis') pose.pelvis = sample(sampler, time, false).map(round);
  }
  result[id] = pose;
}

const header = `// GENERATED by scripts/extract-poses.js - do not edit by hand.
// Single frames of Quaternius's Universal Animation Library (CC0), which
// shares the avatar bodies' skeleton: each bone's local rotation
// [x, y, z, w] and the pelvis's local position. Used by avatar-parts.js
// applyPose for the Condition poses.
//
// SHARED FILE: an identical copy lives in gmscreen/src/js/.
`;
const body = `export const POSE_FRAMES = ${JSON.stringify(result)};\n`;
for (const target of ['src/js/avatar-poses.js', 'gmscreen/src/js/avatar-poses.js']) {
  fs.writeFileSync(path.join(__dirname, '..', target), header + body);
  console.log('wrote', target, `${(Buffer.byteLength(header + body) / 1024).toFixed(1)} KB`);
}
