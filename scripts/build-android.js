// Builds the Android app (android/) - the player app for Android phones,
// tablets and Chromebooks. See android/README.md.
//
//   1. vendors three.js into src/vendor (as npm start / dist do)
//   2. copies the sheet's page files from src/ into the app's assets
//      (android/app/src/main/assets/www, regenerated every build)
//   3. bundles android/web/android-main.js - the Android window.codApi,
//      built around the desktop app's own gmscreen-client.js and
//      campaign-store.js with their Node modules swapped for shims - and
//      loads it into index.html ahead of the sheet's own scripts
//   4. runs Gradle, and copies the APK to release/android/
//
// Usage: npm run android            (debug build - installable on any device)
//        npm run android -- --release   (needs the signing key, see README)
//        npm run android -- --install   (also installs it on the phone over adb)
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');
const esbuild = require('esbuild');

const REPO = path.resolve(__dirname, '..');
const SRC = path.join(REPO, 'src');
const ANDROID = path.join(REPO, 'android');
const WWW = path.join(ANDROID, 'app', 'src', 'main', 'assets', 'www');
const OUT = path.join(REPO, 'release', 'android');

const release = process.argv.includes('--release');
const install = process.argv.includes('--install');

// Desktop-only files: the Electron main process and preload, and the Node
// modules that the bundle in step 3 includes itself.
const SKIP = new Set([
  'main.js',
  'preload.js',
  'js/gmscreen-client.js',
  'js/campaign-store.js',
  'js/campaign-template.js',
  'js/campaign-file.js'
]);

function step(text) {
  console.log(`\n> ${text}`);
}

function copyPage(from, rel = '') {
  for (const entry of fs.readdirSync(path.join(from, rel), { withFileTypes: true })) {
    const relPath = rel ? `${rel}/${entry.name}` : entry.name;
    if (SKIP.has(relPath) || entry.name.startsWith('_')) continue;
    const target = path.join(WWW, relPath);
    if (entry.isDirectory()) {
      fs.mkdirSync(target, { recursive: true });
      copyPage(from, relPath);
    } else {
      fs.copyFileSync(path.join(from, relPath), target);
    }
  }
}

function androidSdk() {
  const local = path.join(ANDROID, 'local.properties');
  if (fs.existsSync(local)) {
    const match = /^sdk\.dir=(.*)$/m.exec(fs.readFileSync(local, 'utf-8'));
    if (match) return match[1].trim().replace(/\\:/g, ':').replace(/\\\\/g, '\\');
  }
  return process.env.ANDROID_HOME || path.join(process.env.LOCALAPPDATA || '', 'Android', 'Sdk');
}

async function main() {
  step('Vendoring three.js');
  execFileSync(process.execPath, [path.join(__dirname, 'vendor-three.js'), REPO], { stdio: 'inherit' });

  step('Copying the sheet into the app');
  fs.rmSync(WWW, { recursive: true, force: true });
  fs.mkdirSync(WWW, { recursive: true });
  copyPage(SRC);

  step('Bundling the Android API');
  const shim = (file) => path.join(ANDROID, 'web', 'shims', file);
  await esbuild.build({
    absWorkingDir: REPO,
    entryPoints: [path.join(ANDROID, 'web', 'android-main.js')],
    outfile: path.join(WWW, 'js', 'android-api.js'),
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: 'es2020',
    alias: {
      http: shim('http.js'),
      'fs/promises': shim('fs-promises.js'),
      events: shim('events.js'),
      'bonjour-service': shim('bonjour.js'),
      crypto: shim('node-globals.js')
    },
    inject: [shim('node-globals.js')], // the global Buffer
    banner: { js: '// Generated by scripts/build-android.js from android/web/ - do not edit.' },
    logLevel: 'warning'
  });

  // A plain script, so it runs (and defines window.codApi) before the
  // sheet's modules; 'self' in the page's CSP covers it.
  const indexPath = path.join(WWW, 'index.html');
  const html = fs.readFileSync(indexPath, 'utf-8');
  const marker = '<script type="importmap">';
  if (!html.includes(marker)) throw new Error('index.html: import map not found - where should android-api.js go?');
  fs.writeFileSync(indexPath, html.replace(marker, `<script src="js/android-api.js"></script>\n${marker}`));

  step(`Building the ${release ? 'release' : 'debug'} APK`);
  const task = [release ? 'assembleRelease' : 'assembleDebug', '--console=plain', '-q'];
  if (process.platform === 'win32') {
    // A .bat file only runs through cmd.
    execFileSync(process.env.ComSpec || 'cmd.exe', ['/d', '/c', path.join(ANDROID, 'gradlew.bat'), ...task], { cwd: ANDROID, stdio: 'inherit' });
  } else {
    execFileSync(path.join(ANDROID, 'gradlew'), task, { cwd: ANDROID, stdio: 'inherit' });
  }

  const variant = release ? 'release' : 'debug';
  const built = path.join(ANDROID, 'app', 'build', 'outputs', 'apk', variant, `app-${variant}.apk`);
  if (!fs.existsSync(built)) throw new Error(`Gradle finished but ${built} isn't there (unsigned release? see android/README.md)`);
  const version = /versionName=(.*)/.exec(fs.readFileSync(path.join(ANDROID, 'version.properties'), 'utf-8'))[1].trim();
  fs.mkdirSync(OUT, { recursive: true });
  const apk = path.join(OUT, `CoD-Characters-${version}${release ? '' : '-debug'}.apk`);
  fs.copyFileSync(built, apk);
  console.log(`\nAPK: ${apk} (${(fs.statSync(apk).size / 1048576).toFixed(1)} MB)`);

  if (install) {
    step('Installing on the connected device');
    const adb = path.join(androidSdk(), 'platform-tools', process.platform === 'win32' ? 'adb.exe' : 'adb');
    execFileSync(adb, ['install', '-r', apk], { stdio: 'inherit' });
  }
}

main().catch((err) => {
  console.error(`\nbuild-android: ${err.message}`);
  process.exit(1);
});
